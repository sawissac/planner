function parse(line: string): EmojiEntry {
  const [emoji, rawName = "", ...keywords] = line.split(" ");
  const name = rawName.replace(/_/g, " ");
  return { emoji, name, search: [name, ...keywords].join(" ").toLowerCase() };
}

export const EMOJI_CATEGORIES: EmojiCategory[] = RAW.map((c) => ({
  id: c.id,
  label: c.label,
  emojis: c.items.map(parse),
}));

const BY_EMOJI = new Map<string, EmojiEntry>();
for (const c of EMOJI_CATEGORIES) {
  for (const e of c.emojis) {
    if (!BY_EMOJI.has(e.emoji)) {
      BY_EMOJI.set(e.emoji, e);
    }
  }
}

/** Look up an emoji's entry; unknown glyphs get a bare entry with no name. */
export function emojiEntry(emoji: string): EmojiEntry {
  return BY_EMOJI.get(emoji) ?? { emoji, name: "", search: "" };
}

/** Every entry whose name or keywords contain each word of `query`. */
export function searchEmoji(query: string): EmojiEntry[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) {
    return [];
  }
  const out: EmojiEntry[] = [];
  for (const e of BY_EMOJI.values()) {
    if (e.emoji === query.trim() || words.every((w) => e.search.includes(w))) {
      out.push(e);
    }
  }
  return out;
}

const RECENT_KEY = "emoji.recent";
const RECENT_MAX = 16;

export function loadRecentEmoji(): string[] {
  try {
    const raw = window.localStorage.getItem(RECENT_KEY);
    const parsed: unknown = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.filter((x): x is string => typeof x === "string") : [];
  } catch {
    return [];
  }
}

export function pushRecentEmoji(emoji: string): string[] {
  const next = [emoji, ...loadRecentEmoji().filter((e) => e !== emoji)].slice(0, RECENT_MAX);
  try {
    window.localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    /* ignore quota / private mode */
  }
  return next;
}
